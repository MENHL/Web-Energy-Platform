INSERT INTO stock_order (order_no, order_type, material_id, material_name, quantity, target, operator, order_time, created_at)
WITH RECURSIVE seq AS (
    SELECT 0 AS n
    UNION ALL
    SELECT n + 1 FROM seq WHERE n < 269
)
SELECT
    CONCAT(IF(MOD(n, 2) = 0, 'RK', 'CK'), '2026', LPAD(8000 + n, 6, '0')) AS order_no,
    IF(MOD(n, 2) = 0, 'INBOUND', 'OUTBOUND') AS order_type,
    MOD(n, 10) + 1 AS material_id,
    ELT(MOD(n, 10) + 1,
        '磷酸铁锂电芯 280Ah', '单晶硅光伏组件 550W', 'IGBT 功率模块 1200V', '组串式逆变器 110kW',
